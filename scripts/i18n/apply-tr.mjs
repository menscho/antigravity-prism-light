// Usage: node scripts/i18n/apply-tr.mjs (apply i18n-work/tr/*.tr.json translations).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const workDir = path.join(root, 'i18n-work', 'tr');
const translation = {};
for (const name of fs.readdirSync(workDir).filter((n) => n.endsWith('.tr.json'))) {
  Object.assign(translation, JSON.parse(fs.readFileSync(path.join(workDir, name), 'utf8')));
}
const missing = [];
const extra = new Set(Object.keys(translation));
function trValue(id, fallback) {
  extra.delete(id);
  const value = translation[id];
  if (value === undefined || value === null || value === '') {
    missing.push(id);
    return fallback;
  }
  return typeof value === 'object' && !Array.isArray(value) ? (value.tr ?? fallback) : value;
}
function replaceLastArrayValue(inner, value) {
  const lastStringRe = /("(?:\\.|[^"\\])*"|'(?:\\.|[^'\\])*')(\s*,?\s*)$/s;
  const match = inner.match(lastStringRe);
  if (!match) return inner;
  const prefix = inner.slice(0, match.index);
  if (!prefix.trimEnd().includes('\n')) return `${prefix.trimEnd()} ${JSON.stringify(String(value))}${match[2].trim().replace(/,$/, '')}`;
  return `${prefix}${JSON.stringify(String(value))}${match[2]}`;
}

// Append Turkish as the ninth locale. The English slot is the required fallback.
const localePath = path.join(root, 'i18n-locales.js');
let localeSource = fs.readFileSync(localePath, 'utf8');
localeSource = localeSource.replace(/,(\r?\n)[ \t]*\r?\n([ \t]*)(?=")/g, ',$1$2');
const arrayStartRe = /([A-Za-z_$][\w$]*):\s*\[/g;
const arraySpans = [];
for (let match; (match = arrayStartRe.exec(localeSource));) {
  const open = arrayStartRe.lastIndex - 1;
  let quote = '', escaped = false, depth = 1, end = open + 1;
  for (; end < localeSource.length && depth; end++) {
    const ch = localeSource[end];
    if (quote) {
      if (escaped) escaped = false;
      else if (ch === '\\') escaped = true;
      else if (ch === quote) quote = '';
    } else if (ch === "'" || ch === '"') quote = ch;
    else if (ch === '[') depth++;
    else if (ch === ']') depth--;
  }
  if (!depth) arraySpans.push({ key: match[1], open, close: end - 1, inner: localeSource.slice(open + 1, end - 1) });
  arrayStartRe.lastIndex = end;
}
for (const span of arraySpans.reverse()) {
  const { key, open, close, inner } = span;
  let values;
  try { values = Function(`return [${inner}]`)(); } catch { continue; }
  if (values.length === 8 || values.length === 9) {
    const id = `ui:${key}`;
    const tr = trValue(id, values[2]);
    if (values.length === 8) {
      const body = inner.replace(/\s*$/, '');
      const comma = /,$/.test(body) ? '' : ',';
      const insertion = !body.includes('\n')
        ? `${body}${comma} ${JSON.stringify(String(tr))}`
        : `${body}${comma}\n      ${JSON.stringify(String(tr))},\n    `;
      localeSource = `${localeSource.slice(0, close)}${insertion}${localeSource.slice(close)}`;
    } else {
      const updatedInner = replaceLastArrayValue(inner, tr);
      localeSource = `${localeSource.slice(0, open + 1)}${updatedInner}${localeSource.slice(close)}`;
    }
  }
}
fs.writeFileSync(localePath, localeSource);

const inlinePath = path.join(root, 'vendor/inline-diff/inline-diff-client.js');
let inlineSource = fs.readFileSync(inlinePath, 'utf8');
const inlineMarker = '    // Turkish locale entries are generated by scripts/i18n/apply-tr.mjs';
const inlineFallbacks = {};
const inlineBlock = inlineSource.match(/const DIFF_FALLBACK = \{([\s\S]*?)\n    \};/);
if (inlineBlock) {
  for (const match of inlineBlock[1].matchAll(/(inlineDiff\w+):\s*\{([\s\S]*?)\n\s*\},/g)) {
    const enMatch = match[2].match(/\ben:\s*'((?:\\.|[^'\\])*)'/);
    if (!enMatch) continue;
    const id = `inline:${match[1]}`;
    const en = Function(`return '${enMatch[1]}'`)();
    inlineFallbacks[match[1]] = trValue(id, en);
  }
  const generated = `${inlineMarker}\n    const TR_INLINE_FALLBACKS = ${JSON.stringify(inlineFallbacks)};\n    for (const [key, value] of Object.entries(TR_INLINE_FALLBACKS)) DIFF_FALLBACK[key].tr = value;`;
  const withoutGenerated = inlineSource.replace(/\s*\/\/ Turkish locale entries are generated by scripts\/i18n\/apply-tr\.mjs[\s\S]*?for \(const \[key, value\] of Object\.entries\(TR_INLINE_FALLBACKS\)\) DIFF_FALLBACK\[key\]\.tr = value;/, '');
  inlineSource = withoutGenerated.replace(/(const DIFF_FALLBACK = \{[\s\S]*?\n    \};)/, `$1\n${generated}`);
  fs.writeFileSync(inlinePath, inlineSource);
}

function updatePipeTable(file, tableName, prefix) {
  const filePath = path.join(root, file);
  let source = fs.readFileSync(filePath, 'utf8');
  const blockRe = new RegExp(`const ${tableName} = \\{([\\s\\S]*?)\\n  \\};`);
  const blockMatch = source.match(blockRe);
  if (!blockMatch) return;
  const english = blockMatch[1].match(/\ben:\s*'((?:\\.|[^'\\])*)'/);
  if (!english) return;
  const englishItems = Function(`return '${english[1]}'`)().split('|');
  const translated = englishItems.map((value, i) => String(trValue(`${prefix}:${i}`, value))).join('|');
  const updatedBlock = blockMatch[0].replace(/\btr:\s*("(?:\\.|[^"\\])*"|'(?:\\.|[^'\\])*')/, `tr: ${JSON.stringify(translated)}`);
  source = source.replace(blockMatch[0], updatedBlock);
  fs.writeFileSync(filePath, source);
}
updatePipeTable('context-menu-btw.js', 'I18N', 'context');
updatePipeTable('host-workbench-enhancer.js', 'UI_RAW', 'workbench');

const omniPath = path.join(root, 'vendor/omni-viewer/workbench-page.mjs');
let omniSource = fs.readFileSync(omniPath, 'utf8');
const omniRe = /export const WORKBENCH_I18N = \{([\s\S]*?)\n\};/;
const omniMatch = omniSource.match(omniRe);
if (omniMatch) {
  const updated = omniMatch[1].replace(/(\w+):\s*\[([^\]]*)\]/g, (whole, key, inner) => {
    let values;
    try { values = Function(`return [${inner}]`)(); } catch { return whole; }
    if (values.length !== 9 && values.length !== 10) return whole;
    const id = `omni:${key}`;
    const translated = String(trValue(id, values[3]));
    if (values.length === 10 && translation[id] === undefined) return whole;
    return `${key}: [${values.slice(0, 9).map((v) => JSON.stringify(v)).join(', ')}, ${JSON.stringify(translated)}]`;
  });
  omniSource = omniSource.replace(omniRe, `export const WORKBENCH_I18N = {${updated}\n};`);
  fs.writeFileSync(omniPath, omniSource);
}

const effortPath = path.join(root, 'vendor/effort-slider/upstream-client.js');
let effortSource = fs.readFileSync(effortPath, 'utf8');
for (const [table, name] of [['SET_TITLE_I18N', 'settingsTitle'], ['SET_HEAD_I18N', 'settingsHeading'], ['FIXED_I18N', 'fixed'], ['EFFORT_TITLE_I18N', 'effortTitle']]) {
  const re = new RegExp(`(var ${table} = \\{[^}]*?\\btr:\\s*)"[^"]*"`);
  const line = effortSource.match(new RegExp(`var ${table} = \\{([^}]+)\\}`));
  const en = line?.[1].match(/\ben:\s*"([^"]*)"/);
  if (en) effortSource = effortSource.replace(re, `$1${JSON.stringify(String(trValue(`effort:${name}`, en[1])))}`);
}
fs.writeFileSync(effortPath, effortSource);

const usagePath = path.join(root, 'usage-core.js');
let usageSource = fs.readFileSync(usagePath, 'utf8');
usageSource = usageSource.replace(/zh-CN,zh-TW,en-US,ja-JP,ko-KR,es-ES,fr-FR,de-DE(?!,tr-TR)/, 'zh-CN,zh-TW,en-US,ja-JP,ko-KR,es-ES,fr-FR,de-DE,tr-TR');
usageSource = usageSource.replace(/\['([^']+)',\s*(\d+),\s*\[([^\]]+)\]\]/g, (whole, id, days, inner) => {
  let labels;
  try { labels = Function(`return [${inner}]`)(); } catch { return whole; }
  if (labels.length !== 8 && labels.length !== 9) return whole;
  const trId = `usage:homeRange:${id}`;
  const translated = String(trValue(trId, labels[2]));
  if (labels.length === 8) return `['${id}', ${days}, [${inner}, ${JSON.stringify(translated)}]]`;
  if (translation[trId] === undefined) return whole;
  return `['${id}', ${days}, [${replaceLastArrayValue(inner, translated)}]]`;
});
fs.writeFileSync(usagePath, usageSource);

function loadSource(file) { return JSON.parse(fs.readFileSync(path.join(root, file), 'utf8')); }
const host = loadSource('vendor/host-i18n/zh-CN.json');
const hostTr = { locale: 'tr', exact: {}, patterns: [] };
for (const key of Object.keys(host.exact || {})) hostTr.exact[key] = trValue(`exact:${key}`, key);
for (const [i, item] of (host.patterns || []).entries()) {
  const id = `pattern:${String(i + 1).padStart(4, '0')}`;
  const groups = [...String(item.regex).matchAll(/\((?!\?)/g)].length;
  const fallback = `English text matching this pattern${groups ? `; captured values: ${Array.from({ length: groups }, (_, n) => `$${n + 1}`).join(', ')}` : ''}. Pattern: ${item.regex}`;
  const replacement = String(trValue(id, fallback));
  const refs = [...replacement.matchAll(/\$(\d+)/g)].map((m) => Number(m[1]));
  const invalid = refs.filter((n) => n < 1 || n > groups);
  if (invalid.length) throw new Error(`${id} replacement references nonexistent regex group(s): ${[...new Set(invalid)].join(', ')}`);
  hostTr.patterns.push({ regex: item.regex, replacement });
}
const hostExtraPath = path.join(root, 'scripts/i18n/tr-extra.json');
if (fs.existsSync(hostExtraPath)) {
  const extras = JSON.parse(fs.readFileSync(hostExtraPath, 'utf8'));
  for (const item of extras.patterns || []) hostTr.patterns.push(item);
}
fs.writeFileSync(path.join(root, 'vendor/host-i18n/tr.json'), `${JSON.stringify(hostTr)}\n`);

const swarm = loadSource('vendor/host-i18n/swarm-zh-CN.json');
const swarmTr = { ...swarm, locale: 'tr', exact: {}, patterns: [], optionPatterns: [], protectedUiKeys: {} };
for (const key of Object.keys(swarm.exact || {})) swarmTr.exact[key] = trValue(`swarm-exact:${key}`, key);
function applyPatternList(list, prefix, output) {
  for (const [i, item] of (list || []).entries()) {
    const id = `${prefix}:${String(i + 1).padStart(4, '0')}`;
    const groups = [...String(item.regex).matchAll(/\((?!\?)/g)].length;
    const fallback = `English text matching this pattern${groups ? `; captured values: ${Array.from({ length: groups }, (_, n) => `$${n + 1}`).join(', ')}` : ''}. Pattern: ${item.regex}`;
    const replacement = String(trValue(id, fallback));
    const refs = [...replacement.matchAll(/\$(\d+)/g)].map((m) => Number(m[1]));
    const invalid = refs.filter((n) => n < 1 || n > groups);
    if (invalid.length) throw new Error(`${id} replacement references nonexistent regex group(s): ${[...new Set(invalid)].join(', ')}`);
    output.push({ regex: item.regex, replacement });
  }
}
applyPatternList(swarm.patterns, 'swarm-pattern', swarmTr.patterns);
applyPatternList(swarm.optionPatterns, 'swarm-option', swarmTr.optionPatterns);
for (const [key, value] of Object.entries(swarm.protectedUiKeys || {})) swarmTr.protectedUiKeys[key] = trValue(`protected:${key}`, value);
fs.writeFileSync(path.join(root, 'vendor/host-i18n/swarm-tr.json'), `${JSON.stringify(swarmTr)}\n`);

